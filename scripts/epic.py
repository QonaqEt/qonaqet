#!/usr/bin/env python3
"""QONAQET — epic claim: iki developer (və onların Claude Code sessiyaları) eyni epic-i işləməsin.

    scripts/epic.py status              # bütün epic-lər: kim işləyir, neçə task açıqdır, götürülə bilərmi
    scripts/epic.py next                # götürülə bilən ilk epic (sırayla, asılılıqları bağlı, boş)
    scripts/epic.py claim E05           # epic-i özünə götür
    scripts/epic.py release E05         # epic-i burax

Claim = epic issue-sunun **assignee**-si. Bu GitHub-da hamıya görünür (issue, board) və `pr-checks`
tərəfindən tətbiq olunur: başqasının epic-inə aid PR qırılır.

Qaydalar (CLAUDE.md → "How Claude Code works"):
  - bir developer eyni anda yalnız bir epic saxlayır
  - epic yalnız `depends:`-dəki epic-lərin hamısı bağlı olanda götürülə bilər (docs/epics/E*.md)
  - eyni anda iki claim olarsa, issue events-də birinci təyin olunan qalır, ikinci geri çəkilir

İstifadəçi: `--user`, yoxsa `QONAQET_DEV` mühit dəyişəni, yoxsa `gh api user`.
Yalnız `gh` CLI (REST) və Python stdlib.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable

ROOT = Path(__file__).resolve().parents[1]
KEY = re.compile(r"^\[(E\d{2})\]")
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

# (method, path, body) → (status, json)
Api = Callable[[str, str, Any], "tuple[int, Any]"]


def gh_api(repo: str) -> Api:
    def call(method: str, path: str, body: Any = None) -> tuple[int, Any]:
        url = path if path.startswith("user") else f"repos/{repo}/{path}"
        cmd = ["gh", "api", "-i", "-X", method, url, "-H", "X-GitHub-Api-Version: 2022-11-28"]
        stdin = None
        if body is not None:
            cmd += ["--input", "-"]
            stdin = json.dumps(body)
        proc = subprocess.run(cmd, input=stdin, capture_output=True, text=True)
        head, _, payload = proc.stdout.replace("\r\n", "\n").partition("\n\n")
        try:
            status = int(head.split()[1])
        except (IndexError, ValueError):
            raise SystemExit(f"gh api cavabı oxunmadı ({method} {path}): {proc.stderr.strip()}")
        try:
            return status, json.loads(payload) if payload.strip() else None
        except json.JSONDecodeError:
            return status, {"message": payload.strip()}

    return call


class ClaimError(Exception):
    pass


@dataclass
class Epic:
    key: str
    number: int
    title: str
    state: str
    assignees: list[str]
    depends: list[str]
    open_tasks: int = 0
    total_tasks: int = 0


def load_depends(epics_dir: Path = ROOT / "docs" / "epics") -> dict[str, list[str]]:
    out = subprocess.run([sys.executable, str(ROOT / "scripts/lib/parse-epics.py"), str(epics_dir)],
                         check=True, capture_output=True, text=True).stdout
    return {e["id"]: e["depends"] for e in json.loads(out)}


def ok(result: tuple[int, Any], what: str) -> Any:
    status, body = result
    if status >= 300:
        raise ClaimError(f"{what}: HTTP {status} {body}")
    return body


def paged(api: Api, path: str) -> list[dict]:
    # --paginate/Link başlığı proxy-də qırılır — açıq page=N ilə.
    items, page, sep = [], 1, "&" if "?" in path else "?"
    while True:
        chunk = ok(api("GET", f"{path}{sep}per_page=100&page={page}", None), path) or []
        items += chunk
        if len(chunk) < 100:
            return items
        page += 1


class Claims:
    def __init__(self, api: Api, user: str, depends: dict[str, list[str]], log: Callable[[str], None] = print):
        self.api, self.user, self.depends, self.log = api, user, depends, log

    def epics(self, with_tasks: bool = False) -> dict[str, Epic]:
        out: dict[str, Epic] = {}
        for issue in paged(self.api, "issues?state=all&labels=epic"):
            match = KEY.match(issue.get("title", ""))
            if not match or "pull_request" in issue:
                continue
            key = match.group(1)
            summary = issue.get("sub_issues_summary") or {}
            out[key] = Epic(
                key=key, number=issue["number"], title=issue["title"], state=issue["state"],
                assignees=[a["login"] for a in issue.get("assignees") or []],
                depends=self.depends.get(key, []),
                open_tasks=summary.get("total", 0) - summary.get("completed", 0),
                total_tasks=summary.get("total", 0),
            )
        return dict(sorted(out.items()))

    def blockers(self, epic: Epic, epics: dict[str, Epic]) -> list[str]:
        return [d for d in epic.depends if d in epics and epics[d].state != "closed"]

    def mine(self, epics: dict[str, Epic]) -> list[Epic]:
        return [e for e in epics.values() if e.state == "open" and self.user in e.assignees]

    # ---------------------------------------------------------- əmrlər
    def status(self) -> str:
        epics = self.epics()
        rows = ["| Epic | Vəziyyət | İşləyən | Task-lar | Gözlədiyi |", "|---|---|---|---|---|"]
        for e in epics.values():
            blockers = self.blockers(e, epics)
            if e.state == "closed":
                state = "✅ bağlı"
            elif e.assignees:
                state = "🔒 işlənir"
            elif blockers:
                state = "⏳ gözləyir"
            else:
                state = "🟢 götürülə bilər"
            who = ", ".join(f"@{a}" for a in e.assignees) or "—"
            tasks = f"{e.total_tasks - e.open_tasks}/{e.total_tasks}" if e.total_tasks else "—"
            rows.append(f"| {e.key} #{e.number} | {state} | {who} | {tasks} | {', '.join(blockers) or '—'} |")
        return "\n".join(rows)

    def next(self) -> Epic | None:
        epics = self.epics()
        for e in epics.values():
            if e.state == "open" and not e.assignees and not self.blockers(e, epics):
                return e
        return None

    def claim(self, key: str) -> Epic:
        epics = self.epics()
        if key not in epics:
            raise ClaimError(f"{key} tapılmadı")
        epic = epics[key]
        if epic.state != "open":
            raise ClaimError(f"{key} bağlıdır")
        others = [a for a in epic.assignees if a != self.user]
        if others:
            raise ClaimError(f"{key} artıq @{others[0]} tərəfindən işlənir — `scripts/epic.py next` ilə başqasını seç")
        if self.user in epic.assignees:
            self.log(f"{key} artıq səndədir")
            return epic
        held = [e.key for e in self.mine(epics) if e.key != key]
        if held:
            raise ClaimError(f"səndə artıq {', '.join(held)} var — əvvəlcə onu bitir və ya `release` et")
        blockers = self.blockers(epic, epics)
        if blockers:
            raise ClaimError(f"{key} hələ {', '.join(blockers)} epic-lərini gözləyir")

        ok(self.api("POST", f"issues/{epic.number}/assignees", {"assignees": [self.user]}), "assign")
        winner = self.first_assignee(epic.number)
        if winner != self.user:
            # Yarış: başqası bizdən əvvəl təyin olunub — geri çəkil.
            self.api("DELETE", f"issues/{epic.number}/assignees", {"assignees": [self.user]})
            raise ClaimError(f"{key}-ni eyni anda @{winner} götürdü (o birinci idi) — başqa epic seç")
        ok(self.api("POST", f"issues/{epic.number}/comments",
                    {"body": f"🔒 **{key}** epic-i @{self.user} tərəfindən götürüldü. Digər developer bu "
                             f"epic-in task-larını götürməsin (`scripts/epic.py status`)." + FOOTER}), "şərh")
        self.log(f"{key} (#{epic.number}) götürüldü → @{self.user}")
        return epic

    def first_assignee(self, number: int) -> str | None:
        """Hazırda təyin olunanlar arasında events-də ən əvvəl təyin olunan."""
        current = {a["login"] for a in ok(self.api("GET", f"issues/{number}", None), "issue").get("assignees") or []}
        for event in paged(self.api, f"issues/{number}/events"):
            login = (event.get("assignee") or {}).get("login")
            if event.get("event") == "assigned" and login in current:
                return login
        return next(iter(sorted(current)), None)

    def release(self, key: str) -> None:
        epics = self.epics()
        if key not in epics:
            raise ClaimError(f"{key} tapılmadı")
        epic = epics[key]
        if self.user not in epic.assignees:
            raise ClaimError(f"{key} səndə deyil (işləyən: {', '.join(epic.assignees) or 'heç kim'})")
        ok(self.api("DELETE", f"issues/{epic.number}/assignees", {"assignees": [self.user]}), "unassign")
        ok(self.api("POST", f"issues/{epic.number}/comments",
                    {"body": f"🔓 **{key}** epic-i @{self.user} tərəfindən buraxıldı." + FOOTER}), "şərh")
        self.log(f"{key} buraxıldı")


def current_user(api: Api, explicit: str | None) -> str:
    if explicit:
        return explicit
    if os.environ.get("QONAQET_DEV"):
        return os.environ["QONAQET_DEV"]
    status, body = api("GET", "user", None)
    if status != 200 or not body:
        raise SystemExit("GitHub istifadəçisi müəyyən olunmadı — `--user <login>` və ya QONAQET_DEV təyin et")
    return body["login"]


def main(argv: list[str] | None = None, api: Api | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["status", "next", "claim", "release"])
    parser.add_argument("epic", nargs="?", help="E00…E20 (claim/release üçün)")
    parser.add_argument("--user")
    parser.add_argument("--repo", default=os.environ.get("REPO", "QonaqEt/qonaqet"))
    args = parser.parse_args(argv)
    api = api or gh_api(args.repo)
    if args.command in ("claim", "release") and not (args.epic and re.fullmatch(r"E\d{2}", args.epic)):
        parser.error("epic açarı lazımdır, məs. E05")
    claims = Claims(api, current_user(api, args.user), load_depends())
    try:
        if args.command == "status":
            print(claims.status())
        elif args.command == "next":
            epic = claims.next()
            print(f"{epic.key} #{epic.number} {epic.title}" if epic else "götürülə bilən epic yoxdur")
        elif args.command == "claim":
            claims.claim(args.epic)
        else:
            claims.release(args.epic)
    except ClaimError as error:
        print(f"XƏTA: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
