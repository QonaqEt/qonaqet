ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "ci" / "dependency-guard.py"
spec = importlib.util.spec_from_file_location("dependency_guard", SCRIPT)
dg = importlib.util.module_from_spec(spec)
sys.modules["dependency_guard"] = dg
spec.loader.exec_module(dg)

SHA = "08c6903cd8c0fde910a37f88322edcfb5dd907a8"


def nuget_lock(direct: list[str], transitive: list[str] = ()) -> str:
    deps = {n: {"type": "Direct", "requested": "[1.0.0, )", "resolved": "1.0.0"} for n in direct}
    deps |= {n: {"type": "Transitive", "resolved": "1.0.0"} for n in transitive}
    deps["Qonaqet.Domain"] = {"type": "Project"}
    return json.dumps({"version": 1, "dependencies": {"net10.0": deps}})


def npm_lock(direct: list[str], dev: list[str] = (), transitive: list[str] = (), workspace_deps: list[str] = ()) -> str:
    packages = {
        "": {"name": "web", "workspaces": ["projects/*"],
             "dependencies": {n: "^1.0.0" for n in direct},
             "devDependencies": {n: "^1.0.0" for n in dev}},
        "projects/ui": {"name": "ui", "dependencies": {n: "^1.0.0" for n in workspace_deps}},
        "node_modules/ui": {"resolved": "projects/ui", "link": True},
    }
    for n in [*direct, *dev, *workspace_deps]:
        packages[f"node_modules/{n}"] = {"version": "1.0.0"}
    for n in transitive:
        packages[f"node_modules/{n}"] = {"version": "1.0.0", "dev": True}
    # eyni adlı iç-içə nüsxə birbaşa sayılmamalıdır
    packages["node_modules/@angular/core/node_modules/tslib"] = {"version": "2.0.0"}
    return json.dumps({"name": "web", "lockfileVersion": 3, "packages": packages})


def pub_lock(entries: dict[str, tuple[str, str]]) -> str:
    out = ["# Generated by pub", "# See https://dart.dev/tools/pub/glossary#lockfile", "packages:"]
    for name, (dependency, source) in entries.items():
        out += [f"  {name}:", f'    dependency: "{dependency}"', "    description:",
                f"      name: {name}", '      url: "https://pub.dev"', f"    source: {source}", '    version: "1.0.0"']
    out += ["sdks:", '  dart: ">=3.5.0 <4.0.0"', '  flutter: ">=3.24.0"']
    return "\n".join(out) + "\n"


class GuardTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        (self.tmp / "docs/dependencies").mkdir(parents=True)
        shutil.copy(ROOT / dg.ALLOWLIST, self.tmp / dg.ALLOWLIST)

    def write(self, rel: str, text: str) -> None:
        path = self.tmp / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    def names(self) -> set[str]:
        return {v.name for v in dg.run(self.tmp)[0]}

    # ---------------------------------------------------------- NuGet
    def test_nuget_allowed_direct_and_any_transitive_pass(self) -> None:
        self.write("backend/src/A/packages.lock.json",
                   nuget_lock(["MongoDB.Driver", "mongodb.driver"], transitive=["System.Text.Json", "DnsClient"]))
        self.assertEqual(self.names(), set())

    def test_nuget_unlisted_direct_fails_with_its_name(self) -> None:
        self.write("backend/src/A/packages.lock.json", nuget_lock(["Newtonsoft.Json"]))
        violations, _ = dg.run(self.tmp)
        self.assertEqual([v.name for v in violations], ["Newtonsoft.Json"])
        self.assertIn("allowlist-də yoxdur", violations[0].reason)
        self.assertIn("Newtonsoft.Json", violations[0].annotation())
        self.assertIn("backend/src/A/packages.lock.json", violations[0].annotation())

    def test_forbidden_package_fails_even_as_transitive(self) -> None:
        self.write("backend/src/A/packages.lock.json", nuget_lock(["MongoDB.Driver"], transitive=["MediatR.Contracts"]))
        violations, _ = dg.run(self.tmp)
        self.assertEqual([v.name for v in violations], ["MediatR.Contracts"])
        self.assertIn("qadağandır (keçid", violations[0].reason)

    # ---------------------------------------------------------- npm
    def test_npm_globs_dev_and_workspace_deps_are_checked(self) -> None:
        self.write("web/package-lock.json",
                   npm_lock(["@angular/core", "rxjs"], dev=["@angular-devkit/build-angular", "left-pad"],
                            transitive=["tslib", "semver"], workspace_deps=["lodash"]))
        self.assertEqual(self.names(), {"left-pad", "lodash"})

    def test_npm_scope_glob_does_not_leak_to_lookalikes(self) -> None:
        self.write("web/package-lock.json", npm_lock(["@angularx/core", "Rxjs"]))
        self.assertEqual(self.names(), {"@angularx/core", "Rxjs"})

    def test_npm_forbidden_scoped_package_is_caught(self) -> None:
        self.write("web/package-lock.json", npm_lock(["@angular/core"], transitive=["@nx/devkit", "nx"]))
        self.assertEqual(self.names(), {"@nx/devkit", "nx"})

    def test_npm_v1_lockfile_is_rejected_loudly(self) -> None:
        self.write("web/package-lock.json", json.dumps({"lockfileVersion": 1, "dependencies": {}}))
        with self.assertRaisesRegex(ValueError, "lockfileVersion 1"):
            dg.run(self.tmp)

    # ---------------------------------------------------------- pub
    def test_pub_direct_checked_sdk_and_transitive_skipped(self) -> None:
        self.write("mobile/pubspec.lock", pub_lock({
            "go_router": ("direct main", "hosted"),
            "flutter": ("direct main", "sdk"),
            "flutter_test": ("direct dev", "sdk"),
            "async": ("transitive", "hosted"),
            "provider": ("direct main", "hosted"),
            "riverpod_lint": ("direct dev", "hosted"),
        }))
        self.assertEqual(self.names(), {"provider", "riverpod_lint"})

    def test_lock_files_under_build_dirs_are_ignored(self) -> None:
        self.write("web/node_modules/x/package-lock.json", npm_lock(["left-pad"]))
        self.write("backend/src/A/obj/packages.lock.json", nuget_lock(["Newtonsoft.Json"]))
        self.assertEqual(self.names(), set())

    # ---------------------------------------------------------- workflows
    def test_workflow_actions_must_be_allowlisted_and_sha_pinned(self) -> None:
        self.write(".github/workflows/x.yml", "\n".join([
            "jobs:", "  a:", "    steps:",
            f"      - uses: actions/checkout@{SHA} # v5",
            "      - uses: actions/setup-node@v4",
            f"      - uses: some-user/cool-action@{SHA}",
            f"      - uses: 'github/codeql-action/init@{SHA}'",
            "      - uses: ./.github/actions/local",
            "      - uses: docker://alpine:3",
        ]))
        self.assertEqual(self.names(), {"actions/setup-node@v4", "some-user/cool-action", "docker://alpine:3"})

    def test_cli_exit_code_and_summary(self) -> None:
        self.write("web/package-lock.json", npm_lock(["left-pad"]))
        result = subprocess.run([sys.executable, str(SCRIPT), str(self.tmp)], capture_output=True, text=True)
        self.assertEqual(result.returncode, 1)
        self.assertIn("::error file=web/package-lock.json", result.stdout)
        self.assertIn("| `web/package-lock.json` | npm | `left-pad` |", result.stdout)
        (self.tmp / "web/package-lock.json").write_text(npm_lock(["rxjs"]), encoding="utf-8")
        ok = subprocess.run([sys.executable, str(SCRIPT), str(self.tmp)], capture_output=True, text=True)
        self.assertEqual(ok.returncode, 0, ok.stdout)


class AllowlistFileTests(unittest.TestCase):
    def setUp(self) -> None:
        self.data = json.loads((ROOT / dg.ALLOWLIST).read_text(encoding="utf-8"))

    def test_every_entry_documents_publisher_and_reason(self) -> None:
        for ecosystem in ("nuget", "npm", "pub", "github-actions"):
            for entry in self.data[ecosystem]:
                for field in ("name", "publisher", "reason"):
                    self.assertTrue(entry.get(field), f"{ecosystem}: {entry} → '{field}' yoxdur")
                if ecosystem != "github-actions":
                    self.assertTrue(entry.get("license"), f"{ecosystem}: {entry['name']} → lisenziya yoxdur")

    def test_no_allowlisted_package_is_also_forbidden(self) -> None:
        allow = dg.Allowlist(self.data)
        for ecosystem in ("nuget", "npm", "pub"):
            for entry in self.data[ecosystem]:
                self.assertIsNone(allow.forbidden_reason(entry["name"]), entry["name"])

    def test_workflow_denies_every_forbidden_license(self) -> None:
        workflow = (ROOT / ".github/workflows/dependency-guard.yml").read_text(encoding="utf-8")
        denied = re.search(r"deny-licenses:\s*(.+)", workflow).group(1)
        for license_id in self.data["policy"]["forbidden_licenses"]:
            self.assertIn(license_id, denied, f"{license_id} dependency-review-action-da bloklanmır")


if __name__ == "__main__":
    unittest.main()
