from __future__ import annotations

import importlib.util
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("epic_progress", ROOT / "scripts" / "ci" / "epic-progress.py")
ep = importlib.util.module_from_spec(spec)
sys.modules["epic_progress"] = ep
spec.loader.exec_module(ep)


def issue(number, title, labels=(), state="open", reason=None):
    return {"number": number, "title": title, "state": state, "state_reason": reason,
            "labels": [{"name": n} for n in labels]}


class FakeGitHub:
    def __init__(self, task_states, epic_title="[E00] Repo", epic_labels=("epic",)) -> None:
        self.issues = {1: issue(1, epic_title, epic_labels)}
        self.children = {1: []}
        for i, (state, reason) in enumerate(task_states, start=2):
            self.issues[i] = issue(i, f"[E00-T{i - 1:02d}] task {i}", ("task",), state, reason)
            self.children[1].append(i)
        self.issues[50] = issue(50, "loose", ("task",), "closed")
        self.comments: dict[int, list[dict]] = {1: [{"body": "başqa şərh"}]}
        self.tags: dict[str, str] = {}
        self.writes: list[tuple[str, str]] = []
        self.fail_tag = False

    def __call__(self, method, path, body):
        if method != "GET":
            self.writes.append((method, path))
        base, _, query = path.partition("?")
        page = int(query.rsplit("page=", 1)[1]) if "page=" in query else 1
        parts = base.split("/")
        if base == "git/ref/heads/main":
            return 200, {"object": {"sha": "a" * 40}}
        if base.startswith("git/ref/tags/"):
            name = base.removeprefix("git/ref/tags/")
            return (200, {"ref": name}) if name in self.tags else (404, {"message": "Not Found"})
        if base == "git/refs":
            if self.fail_tag:
                return 422, {"message": "boom"}
            self.tags[body["ref"].removeprefix("refs/tags/")] = body["sha"]
            return 201, {}
        number = int(parts[1])
        if len(parts) == 3 and parts[2] == "parent":
            parent = next((p for p, kids in self.children.items() if number in kids), None)
            return (200, self.issues[parent]) if parent else (404, {"message": "Not Found"})
        if len(parts) == 3 and parts[2] == "sub_issues":
            kids = [self.issues[k] for k in self.children.get(number, [])]
            return 200, kids[(page - 1) * 100: page * 100]
        if len(parts) == 3 and parts[2] == "comments":
            if method == "POST":
                self.comments.setdefault(number, []).append(body)
                return 201, body
            return 200, self.comments.get(number, [])[(page - 1) * 100: page * 100]
        if method == "PATCH":
            self.issues[number].update(body)
            return 200, self.issues[number]
        return 200, self.issues[number]


def run(gh, number=2):
    return ep.run(gh, number, log=lambda _: None)


class EpicProgressTests(unittest.TestCase):
    def test_open_tasks_keep_the_epic_open(self) -> None:
        gh = FakeGitHub([("closed", "completed"), ("open", None)])
        self.assertEqual(run(gh), "in-progress")
        self.assertEqual(gh.writes, [])

    def test_last_task_closes_epic_comments_and_tags(self) -> None:
        gh = FakeGitHub([("closed", "completed"), ("closed", "completed"), ("closed", "not_planned")])
        self.assertEqual(run(gh, 4), "done")
        self.assertEqual(gh.issues[1]["state"], "closed")
        self.assertEqual(gh.issues[1]["state_reason"], "completed")
        self.assertEqual(gh.tags, {"epic-E00-done": "a" * 40})
        comment = gh.comments[1][-1]["body"]
        self.assertIn(ep.MARKER, comment)
        self.assertIn("**2** task tamamlandı, **1** planlaşdırılmadı.", comment)
        self.assertIn("- [x] #2 ", comment)
        self.assertIn("~~#4 ", comment)
        self.assertIn("_Generated by [Claude Code]", comment)

    def test_second_run_is_a_no_op(self) -> None:
        gh = FakeGitHub([("closed", "completed")])
        run(gh)
        gh.writes.clear()
        self.assertEqual(run(gh), "done")
        self.assertEqual(gh.writes, [])
        self.assertEqual(sum(ep.MARKER in c["body"] for c in gh.comments[1]), 1)

    def test_a_half_finished_run_is_completed_without_duplicates(self) -> None:
        gh = FakeGitHub([("closed", "completed")])
        gh.fail_tag = True
        with self.assertRaises(ep.EpicError):
            run(gh)
        self.assertEqual(gh.issues[1]["state"], "closed")
        gh.fail_tag = False
        run(gh)
        self.assertIn("epic-E00-done", gh.tags)
        self.assertEqual(sum(ep.MARKER in c["body"] for c in gh.comments[1]), 1)

    def test_issue_without_parent_or_with_non_epic_parent_is_ignored(self) -> None:
        gh = FakeGitHub([("closed", "completed")])
        self.assertEqual(run(gh, 50), "no-parent")
        gh = FakeGitHub([("closed", "completed")], epic_labels=("task",))
        self.assertEqual(run(gh), "not-epic")
        self.assertEqual(gh.writes, [])

    def test_more_than_one_page_of_sub_issues(self) -> None:
        gh = FakeGitHub([("closed", "completed")] * 120 + [("open", None)])
        self.assertEqual(run(gh), "in-progress")
        gh.issues[122]["state"] = "closed"
        self.assertEqual(run(gh), "done")
        self.assertIn("**121** task", gh.comments[1][-1]["body"])

    def test_epic_without_key_is_an_explicit_error(self) -> None:
        gh = FakeGitHub([("closed", "completed")], epic_title="Repo epic")
        with self.assertRaisesRegex(ep.EpicError, r"\[Exx\]"):
            run(gh)


if __name__ == "__main__":
    unittest.main()
