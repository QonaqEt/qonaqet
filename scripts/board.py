#!/usr/bin/env python3
"""QONAQET board — docs/epics/*.md fayllarından docs/BOARD.md yaradır (ADR 0004).

    scripts/board.py           # docs/BOARD.md-ni yenidən yaz
    scripts/board.py --check   # fayl aktual deyilsə 1 ilə çıx (CI)
    scripts/board.py --root D  # başqa repo kökü (testlər)

BOARD.md heç vaxt əl ilə redaktə olunmur: mənbə epic fayllarıdır. Yalnız Python stdlib.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Windows konsolunda (cp1252) ə, ✅ kimi simvollar çap oluna bilsin.
sys.stdout.reconfigure(encoding="utf-8")
sys.stderr.reconfigure(encoding="utf-8")

EPICS = ROOT / "docs" / "epics"

ICON = {"todo": "⬜", "in-progress": "🔄", "done": "✅", "dropped": "🚫"}


def load(epics_dir: Path = EPICS) -> list[dict]:
    out = subprocess.run([sys.executable, str(ROOT / "scripts/lib/parse-epics.py"), str(epics_dir)],
                         check=True, capture_output=True, encoding="utf-8").stdout
    return json.loads(out)


def progress(epic: dict) -> tuple[int, int]:
    live = [t for t in epic["tasks"] if t["status"] != "dropped"]
    return sum(t["status"] == "done" for t in live), len(live)


def claimable(epic: dict, by_id: dict[str, dict]) -> bool:
    return epic["status"] == "todo" and not epic["owner"] and all(by_id[d]["status"] == "done" for d in epic["depends"])


def render(epics: list[dict]) -> str:
    by_id = {e["id"]: e for e in epics}
    lines = [
        "<!-- GENERATED by scripts/board.py from docs/epics/*.md — do not edit by hand. -->",
        "# QONAQET board",
        "",
        "Mənbə: `docs/epics/Exx.md`. Dəyişmək üçün: `scripts/epic.py claim|release|task`, sonra `scripts/board.py`.",
        "",
        "## Epic-lər",
        "",
        "| Epic | Ad | Status | İşləyən | Task-lar | Gözlədiyi |",
        "|---|---|---|---|---|---|",
    ]
    for e in epics:
        done, total = progress(e)
        waiting = [d for d in e["depends"] if by_id[d]["status"] != "done"]
        status = f"{ICON[e['status']]} {e['status']}"
        if claimable(e, by_id):
            status += " · 🟢 götürülə bilər"
        owner = f"@{e['owner']}" if e["owner"] else "—"
        lines.append(f"| [{e['id']}](epics/{e['id']}.md) | {e['title']} | {status} | {owner} | {done}/{total} | "
                     f"{', '.join(waiting) or '—'} |")

    lines += ["", "## Hazırda işlənən task-lar", ""]
    active = [(e, t) for e in epics for t in e["tasks"] if t["status"] == "in-progress"]
    if active:
        lines += ["| Task | Ad | Epic sahibi |", "|---|---|---|"]
        lines += [f"| {t['key']} | {t['title']} | {'@' + e['owner'] if e['owner'] else '—'} |" for e, t in active]
    else:
        lines.append("Yoxdur.")

    for e in epics:
        done, total = progress(e)
        owner = f" · @{e['owner']}" if e["owner"] else ""
        lines += ["", f"## {e['id']} — {e['title']}", "",
                  f"{ICON[e['status']]} {e['status']}{owner} · {done}/{total} task", "",
                  "| | Task | Ad | Area | Priority | Size |", "|---|---|---|---|---|---|"]
        for t in e["tasks"]:
            flags = "".join(f" `{label}`" for label in t["extra_labels"])
            lines.append(f"| {ICON[t['status']]} | {t['key']} | {t['title']}{flags} | {t['area']} | {t['priority']} | {t['size']} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    root = Path(argv[argv.index("--root") + 1]) if "--root" in argv else ROOT
    board = root / "docs" / "BOARD.md"
    text = render(load(root / "docs" / "epics"))
    if "--check" in argv:
        current = board.read_text(encoding="utf-8") if board.exists() else ""
        if current != text:
            print("::error file=docs/BOARD.md::docs/BOARD.md aktual deyil — `python3 scripts/board.py` işlət və commit et")
            return 1
        print("docs/BOARD.md aktualdır")
        return 0
    board.write_text(text, encoding="utf-8")
    print(f"yazıldı: {board}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
