#!/usr/bin/env python3
"""QONAQET epic-progress — task bağlananda epic-in tamamlanmasını yoxlayır (E00-T11).

    epic-progress.py <bağlanan issue nömrəsi>

Mühit: GITHUB_TOKEN, REPO. Yalnız REST və Python stdlib.

Bağlanan issue-nun valideyni `epic` label-li issue-dursa və onun BÜTÜN sub-issue-ları bağlıdırsa:
  1. epic-ə xülasə şərhi yazılır (gizli marker ilə — təkrar yazılmır)
  2. epic bağlanır (state_reason=completed) → built-in "Item closed" workflow-u onu `Done`-a keçirir
  3. `main`-in HEAD-ində `epic-Exx-done` tag-ı yaradılır (varsa toxunulmur)
Hər addım ayrıca idempotentdir: yarımçıq qalmış qaçışı təkrar işə salmaq qalanını tamamlayır.
"""
from __future__ import annotations

import json
import os
import re
import sys
import urllib.error
import urllib.request
from typing import Any, Callable

KEY = re.compile(r"^\[(E\d{2})\]")
MARKER = "<!-- epic-progress:done -->"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

# (method, path, body) → (status, json)
Api = Callable[[str, str, Any], "tuple[int, Any]"]


def github_api(repo: str, token: str) -> Api:
    def call(method: str, path: str, body: Any = None) -> tuple[int, Any]:
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(f"https://api.github.com/repos/{repo}/{path}", data=data, method=method, headers={
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "Content-Type": "application/json",
        })
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                raw = resp.read()
                return resp.status, json.loads(raw) if raw else None
        except urllib.error.HTTPError as error:
            raw = error.read()
            try:
                return error.code, json.loads(raw) if raw else None
            except json.JSONDecodeError:
                return error.code, {"message": raw.decode(errors="replace")}

    return call


class EpicError(Exception):
    pass


def ok(result: tuple[int, Any], what: str) -> Any:
    status, body = result
    if status >= 300:
        raise EpicError(f"{what}: HTTP {status} {body}")
    return body


def paged(api: Api, path: str) -> list[dict]:
    # --paginate/Link başlığı proxy-də qırılır — açıq page=N ilə.
    items, page = [], 1
    sep = "&" if "?" in path else "?"
    while True:
        chunk = ok(api("GET", f"{path}{sep}per_page=100&page={page}", None), path) or []
        items += chunk
        if len(chunk) < 100:
            return items
        page += 1


def summary(epic: dict, tasks: list[dict]) -> str:
    done = [t for t in tasks if t.get("state_reason") != "not_planned"]
    skipped = [t for t in tasks if t.get("state_reason") == "not_planned"]
    lines = [MARKER, f"## ✅ {epic['title']} — bütün task-lar bağlandı", ""]
    lines.append(f"**{len(done)}** task tamamlandı" + (f", **{len(skipped)}** planlaşdırılmadı." if skipped else "."))
    lines.append("")
    lines += [f"- [x] #{t['number']} {t['title']}" for t in done]
    lines += [f"- [ ] ~~#{t['number']} {t['title']}~~ (not planned)" for t in skipped]
    lines += ["", "Epic bağlanır və `Done`-a keçir. `CLAUDE.md` → \"How Claude Code works\", 5: epic-in acceptance "
              "criteria-sını yoxla və `README.md`/`docs/`-u yenilə."]
    return "\n".join(lines) + FOOTER


def run(api: Api, closed_number: int, log: Callable[[str], None] = print) -> str:
    status, parent = api("GET", f"issues/{closed_number}/parent", None)
    if status == 404 or not parent:
        log(f"#{closed_number}-in valideyni yoxdur — heç nə edilmir")
        return "no-parent"
    ok((status, parent), "valideyn")
    if "epic" not in {label["name"] for label in parent.get("labels", [])}:
        log(f"valideyn #{parent['number']} epic deyil — heç nə edilmir")
        return "not-epic"
    key = KEY.match(parent.get("title", ""))
    if not key:
        raise EpicError(f"epic #{parent['number']} başlığında [Exx] açarı yoxdur: {parent.get('title')}")
    epic_no = parent["number"]

    tasks = paged(api, f"issues/{epic_no}/sub_issues")
    still_open = [t for t in tasks if t.get("state") != "closed"]
    if not tasks or still_open:
        log(f"{key.group(1)}: {len(tasks) - len(still_open)}/{len(tasks)} bağlıdır — epic açıq qalır")
        return "in-progress"

    comments = paged(api, f"issues/{epic_no}/comments")
    if any(MARKER in (c.get("body") or "") for c in comments):
        log("xülasə şərhi artıq var")
    else:
        ok(api("POST", f"issues/{epic_no}/comments", {"body": summary(parent, tasks)}), "şərh")
        log("xülasə şərhi yazıldı")

    if parent.get("state") != "closed":
        ok(api("PATCH", f"issues/{epic_no}", {"state": "closed", "state_reason": "completed"}), "epic-in bağlanması")
        log(f"#{epic_no} bağlandı")

    tag = f"epic-{key.group(1)}-done"
    status, _ = api("GET", f"git/ref/tags/{tag}", None)
    if status == 200:
        log(f"tag {tag} artıq var")
    else:
        sha = ok(api("GET", "git/ref/heads/main", None), "main")["object"]["sha"]
        ok(api("POST", "git/refs", {"ref": f"refs/tags/{tag}", "sha": sha}), "tag")
        log(f"tag {tag} → {sha[:7]}")
    return "done"


def main(argv: list[str]) -> int:
    if len(argv) != 2 or not argv[1].isdigit():
        print(__doc__, file=sys.stderr)
        return 2
    api = github_api(os.environ["REPO"], os.environ["GITHUB_TOKEN"])
    try:
        run(api, int(argv[1]))
    except EpicError as error:
        print(f"::error title=epic-progress::{error}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
